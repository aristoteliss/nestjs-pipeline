import { RootDomainOutcome } from '../../domain/outcomes/root-domain.outcome';
import type { CommandRepository } from '../command-repository.abstract';

/**
 * Write-through cache decorator for a {@link CommandRepository} `save` method.
 *
 * Provides declarative cache synchronization on mutating database operations:
 * - **Write-through update**: When `save()` resolves with a non-nullish result, the result is cached
 *   under the key generated by `setKeyFn` (after invalidating any secondary keys via `invalidateKeysFn`).
 * - **Cache eviction on delete**: When `save()` resolves with `null` or `undefined` (e.g. entity deletion),
 *   all keys returned by `deleteKeysFn` are evicted from the cache.
 * - **Best-effort safety**: Cache write and eviction operations swallow errors internally so that an
 *   already-committed database transaction is never converted into an application error.
 * - **No entity coupling**: Cache keys are derived externally via provided key functions or helpers
 *   (e.g., `filterCacheKey`), keeping domain aggregates completely free of caching concerns.
 *
 * @param setKeyFn - Function deriving the cache key to write on success, or `null` to skip caching. Defaults to entity ID.
 * @param deleteKeysFn - Function deriving keys to evict when `save()` returns `null`/`undefined`, or `null` to skip. Defaults to `[entity.id]`.
 * @param invalidateKeysFn - Optional secondary keys to evict on every successful save before writing the new entry.
 *
 * @example Write-through caching on user creation / update
 * ```typescript
 * @Injectable()
 * export class UpdateUserCommandRepository extends CommandRepository<UserUpdateOutcome> {
 *   @Cache<UserUpdateOutcome, UserSnapshot>(
 *     (outcome) => filterCacheKey('user', { id: outcome.entity.id }),
 *     null,
 *     (outcome) => [filterCacheKey('user', { email: outcome.entity.email })],
 *   )
 *   async save(outcome: UserUpdateOutcome): Promise<UserSnapshot> {
 *     const user = await this.store.em.upsert(User, outcome.entity);
 *     return user.toJSON();
 *   }
 * }
 * ```
 *
 * @example Cache eviction on user deletion
 * ```typescript
 * @Injectable()
 * export class DeleteUserCommandRepository extends CommandRepository<UserUpdateOutcome> {
 *   @Cache<UserUpdateOutcome, UserSnapshot>(
 *     null,
 *     (outcome) => [
 *       filterCacheKey('user', { id: outcome.entity.id }),
 *       filterCacheKey('user', { email: outcome.entity.email }),
 *     ],
 *   )
 *   async save(outcome: UserUpdateOutcome): Promise<null> {
 *     await this.store.em.nativeDelete(User, outcome.entity.id);
 *     return null;
 *   }
 * }
 * ```
 */
export function Cache<
  TDomainOutcome extends RootDomainOutcome,
  TResult = unknown | null,
>(
  setKeyFn: ((domainOutcome: TDomainOutcome) => string) | null = (outcome) =>
    outcome.entity.id,
  deleteKeysFn: ((domainOutcome: TDomainOutcome) => string[]) | null = (
    outcome,
  ) => [outcome.entity.id],
  invalidateKeysFn: ((domainOutcome: TDomainOutcome) => string[]) | null = null,
): MethodDecorator {
  return (
    _target: object,
    _propertyKey: string | symbol,
    descriptor: PropertyDescriptor,
  ) => {
    const original = descriptor.value as (
      domainOutcome: TDomainOutcome,
    ) => Promise<TResult | null>;

    descriptor.value = async function (
      this: CommandRepository<TDomainOutcome, unknown | null>,
      domainOutcome: TDomainOutcome,
    ): Promise<TResult | null> {
      const result = await original.call(this, domainOutcome);

      if (!this.cache) {
        return result;
      }

      // Cache maintenance is best-effort: the DB write already succeeded,
      // so a cache failure must not turn a success into an error (which
      // would cause idempotency release-on-error to drop the claim).
      if (result === null || result === undefined) {
        if (deleteKeysFn) {
          for (const key of deleteKeysFn(domainOutcome)) {
            try {
              await this.cache.delete(key);
            } catch {
              /* best-effort */
            }
          }
        }
        return result;
      }

      if (invalidateKeysFn) {
        for (const key of invalidateKeysFn(domainOutcome)) {
          try {
            await this.cache.delete(key);
          } catch {
            /* best-effort */
          }
        }
      }

      if (setKeyFn) {
        try {
          await this.cache.set(setKeyFn(domainOutcome), result);
        } catch {
          /* best-effort */
        }
      }

      return result;
    };
  };
}
