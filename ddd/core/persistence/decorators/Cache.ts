import type { CommandRepository } from '../command-repository.abstract';

/**
 * Options for configuring write-through and eviction caching via {@link Cache}.
 */
export interface CacheOptions<TEntity = unknown> {
  /**
   * Function deriving the cache key to write on success.
   * Pass `null` or omit to skip write-through caching.
   */
  setKey?: ((entity: TEntity) => string) | null;

  /**
   * Function deriving keys to evict when `save()` returns `null` or `undefined` (e.g. deletion).
   */
  deleteKeys?: ((entity: TEntity) => string[]) | null;

  /**
   * Optional secondary keys to evict on every successful save before writing the new entry.
   */
  invalidateKeys?: ((entity: TEntity) => string[]) | null;
}

/**
 * Write-through cache decorator for a {@link CommandRepository} `save` method.
 *
 * Provides declarative cache synchronization on mutating database operations:
 * - **Write-through update**: When `save()` resolves with a non-nullish result, the result is cached
 *   under the key generated by `setKey` (after invalidating any secondary keys via `invalidateKeys`).
 * - **Cache eviction on delete**: When `save()` resolves with `null` or `undefined` (e.g. entity deletion),
 *   all keys returned by `deleteKeys` are evicted from the cache.
 * - **Best-effort safety**: Cache write and eviction operations swallow errors internally so that an
 *   already-committed database transaction is never converted into an application error.
 * - **Explicit key derivation**: Requires explicit key derivation functions or options to prevent
 *   unscoped or ambiguous key collisions across multi-tenant boundaries.
 *
 * @example Positional syntax on creation / update
 * ```typescript
 * @Cache<User, UserSnapshot>(
 *   (user) => filterCacheKey(User.aggregateName, { id: user.id }),
 *   null,
 *   (user) => [filterCacheKey(User.aggregateName, { email: user.email })],
 * )
 * async save(user: User): Promise<UserSnapshot> { ... }
 * ```
 *
 * @example Options object syntax on eviction / delete
 * ```typescript
 * @Cache<User, null>({
 *   deleteKeys: (user) => [
 *     filterCacheKey(User.aggregateName, { id: user.id }),
 *     filterCacheKey(User.aggregateName, { email: user.email }),
 *   ],
 * })
 * async save(user: User): Promise<null> { ... }
 * ```
 */
export function Cache<TEntity = unknown, TResult = unknown | null>(
  setKeyOrOptions: ((entity: TEntity) => string) | CacheOptions<TEntity> | null,
  deleteKeysFn?: ((entity: TEntity) => string[]) | null,
  invalidateKeysFn?: ((entity: TEntity) => string[]) | null,
): MethodDecorator {
  let resolvedSetKey: ((entity: TEntity) => string) | null = null;
  let resolvedDeleteKeys: ((entity: TEntity) => string[]) | null = null;
  let resolvedInvalidateKeys: ((entity: TEntity) => string[]) | null = null;

  if (typeof setKeyOrOptions === 'function') {
    resolvedSetKey = setKeyOrOptions;
    resolvedDeleteKeys = deleteKeysFn ?? null;
    resolvedInvalidateKeys = invalidateKeysFn ?? null;
  } else if (setKeyOrOptions && typeof setKeyOrOptions === 'object') {
    resolvedSetKey = setKeyOrOptions.setKey ?? null;
    resolvedDeleteKeys = setKeyOrOptions.deleteKeys ?? null;
    resolvedInvalidateKeys = setKeyOrOptions.invalidateKeys ?? null;
  } else if (setKeyOrOptions === null) {
    resolvedSetKey = null;
    resolvedDeleteKeys = deleteKeysFn ?? null;
    resolvedInvalidateKeys = invalidateKeysFn ?? null;
  } else {
    throw new Error(
      '@Cache decorator requires an explicit key derivation function or options object.',
    );
  }

  if (!resolvedSetKey && !resolvedDeleteKeys && !resolvedInvalidateKeys) {
    throw new Error(
      '@Cache decorator requires at least one of setKey, deleteKeys, or invalidateKeys to be specified.',
    );
  }

  return (
    _target: object,
    _propertyKey: string | symbol,
    descriptor: PropertyDescriptor,
  ) => {
    const original = descriptor.value as (
      entity: TEntity,
    ) => Promise<TResult | null>;

    descriptor.value = async function (
      this: CommandRepository<TEntity, unknown | null>,
      entity: TEntity,
    ): Promise<TResult | null> {
      const result = await original.call(this, entity);

      if (!this.cache) {
        return result;
      }

      // Cache maintenance is best-effort: the DB write already succeeded,
      // so a cache failure must not turn a success into an error (which
      // would cause idempotency release-on-error to drop the claim).
      if (result === null || result === undefined) {
        if (resolvedDeleteKeys) {
          for (const key of resolvedDeleteKeys(entity)) {
            try {
              await this.cache.delete(key);
            } catch {
              /* best-effort */
            }
          }
        }
        return result;
      }

      if (resolvedInvalidateKeys) {
        for (const key of resolvedInvalidateKeys(entity)) {
          try {
            await this.cache.delete(key);
          } catch {
            /* best-effort */
          }
        }
      }

      if (resolvedSetKey) {
        try {
          await this.cache.set(resolvedSetKey(entity), result);
        } catch {
          /* best-effort */
        }
      }

      return result;
    };
  };
}
